#!/bin/sh
# SurveillanceHound — native (non-Docker) install on a Linux host.
#
# The Docker path in this directory's README needs a registry and a
# Debian mirror at build time. On a camera segment that is often exactly
# what you do not have: the NVR here reaches deb.debian.org on :80 and
# nothing on :443, so `docker compose build` cannot run while the daemon
# itself needs no network at all. Hence this.
#
# Zero dependencies, by the same trick the OPNsense installer uses: the
# daemon is stdlib-only, so there is nothing to pip-install. A .pth puts
# `src/` on the interpreter's path and a three-line wrapper becomes
# /usr/local/bin/hound. Nothing to break on the next apt upgrade, and no
# virtualenv to go stale.
#
#   sudo sh deploy/agent/install-native.sh
#
# Idempotent — re-run it to update after a `git pull`. It will NOT
# overwrite an existing config, and it does not start the service: a
# relay agent needs the collector's certificate pin first, and starting
# a monitor before it is configured teaches an operator to ignore it.
#
# Env overrides: SRC_DIR CONFIG HOUND_USER STATE_DIR LOG_DIR
set -eu

SRC_DIR=${SRC_DIR:-/opt/surveillancehound}
CONFIG=${CONFIG:-/etc/hound.toml}
HOUND_USER=${HOUND_USER:-hound}
STATE_DIR=${STATE_DIR:-/var/lib/hound}
LOG_DIR=${LOG_DIR:-/var/log/hound}
UNIT=/etc/systemd/system/hound.service

say()  { printf '\033[36m▸\033[0m %s\n' "$*"; }
ok()   { printf '\033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '\033[33m!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" = 0 ] || die "run as root (sudo sh $0)"

# --- 1. prerequisites -------------------------------------------------
PY=$(command -v python3) || die "python3 not found"
"$PY" - <<'EOF' || die "python 3.11+ required (tomllib)"
import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)
EOF
ok "python: $PY ($("$PY" -c 'import sys;print(".".join(map(str,sys.version_info[:3])))'))"

command -v tcpdump >/dev/null || die "tcpdump not found (apt install tcpdump)"
TCPDUMP=$(command -v tcpdump)
ok "tcpdump: $TCPDUMP"

# --- 2. source tree ---------------------------------------------------
# Called from a checkout: copy it. Already installed: leave it alone and
# just refresh, so `git pull && re-run` works from either direction.
here=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)
if [ -d "$here/src/surveillancehound" ]; then
    if [ "$here" != "$SRC_DIR" ]; then
        say "copying source: $here -> $SRC_DIR"
        mkdir -p "$SRC_DIR"
        # -a to keep modes; delete nothing else under SRC_DIR
        cp -a "$here/src" "$here/pyproject.toml" "$SRC_DIR/" 2>/dev/null \
            || cp -a "$here/src" "$SRC_DIR/"
    fi
else
    [ -d "$SRC_DIR/src/surveillancehound" ] \
        || die "no source tree here or at $SRC_DIR"
fi
ok "source: $SRC_DIR/src"

# --- 3. the CLI, without pip ------------------------------------------
SITEPKG=$("$PY" -c 'import site; print(site.getsitepackages()[0])')
printf '%s\n' "$SRC_DIR/src" > "$SITEPKG/surveillancehound.pth"
cat > /usr/local/bin/hound <<EOF
#!/bin/sh
# SurveillanceHound CLI wrapper (generated by install-native.sh)
exec $PY -m surveillancehound.cli "\$@"
EOF
chmod 0755 /usr/local/bin/hound
ok "hound CLI: /usr/local/bin/hound (via $SITEPKG/surveillancehound.pth)"

# --- 4. state + log dirs ----------------------------------------------
# The shipped unit uses DynamicUser=yes with StateDirectory= and
# LogsDirectory=, so systemd owns the uid AND the directories. Creating
# a service user here would be cruft the unit never looks at, and
# pointing the config at /var/lib/hound while systemd runs the daemon
# under /var/lib/surveillancehound is how you get a monitor that starts,
# writes nowhere you are looking, and reports nothing.
#
# So: read the directory names OUT of the unit rather than assuming,
# and only create a user if the unit does not do it for us.
unit_src=$here/deploy/hound.service
dynuser=no
if [ -f "$unit_src" ] && grep -qiE '^DynamicUser=yes' "$unit_src"; then
    dynuser=yes
    sd=$(sed -nE 's/^StateDirectory=(.*)$/\1/p' "$unit_src" | head -1)
    ld=$(sed -nE 's/^LogsDirectory=(.*)$/\1/p' "$unit_src" | head -1)
    STATE_DIR=/var/lib/${sd:-surveillancehound}
    LOG_DIR=/var/log/${ld:-surveillancehound}
    ok "DynamicUser=yes — systemd owns the uid; no service user created"
fi
if [ "$dynuser" = no ] && ! id "$HOUND_USER" >/dev/null 2>&1; then
    useradd --system --home-dir "$STATE_DIR" --shell /usr/sbin/nologin \
            "$HOUND_USER"
    ok "created user $HOUND_USER"
fi
# systemd creates these on start; make them now so a manual
# `hound run` before the first `systemctl start` works too.
install -d -m 0750 "$STATE_DIR"
install -d -m 0755 "$LOG_DIR"
ok "state: $STATE_DIR   logs: $LOG_DIR"

# --- 5. unprivileged capture ------------------------------------------
# For running `hound run` BY HAND as a non-root user. The systemd unit
# does not need this — it grants CAP_NET_RAW ambiently, and verified on
# Debian 13 the file caps neither help nor hinder it. Harmless to have
# both, and without it a manual run as yourself cannot capture.
if command -v setcap >/dev/null 2>&1; then
    setcap cap_net_raw,cap_net_admin=eip "$TCPDUMP" \
        && ok "setcap on $TCPDUMP (capture without root)"
else
    warn "setcap not found (apt install libcap2-bin) — capture will need root"
fi

# --- 6. systemd unit --------------------------------------------------
if [ -f "$here/deploy/hound.service" ]; then
    sed "s#^ExecStart=.*#ExecStart=/usr/local/bin/hound run $CONFIG#" \
        "$here/deploy/hound.service" > "$UNIT"
    systemctl daemon-reload
    ok "unit: $UNIT (ExecStart -> $CONFIG)"
else
    warn "deploy/hound.service not found; unit not installed"
fi

# --- 7. config, never clobbered ---------------------------------------
if [ -f "$CONFIG" ]; then
    ok "config exists, left untouched: $CONFIG"
else
    warn "no config at $CONFIG — copy deploy/agent/hound.toml.example and edit it"
fi

printf '\n'
say "Paths the service will actually use:"
printf '  store  -> %s/hound.sqlite\n' "$STATE_DIR"
printf '  logs   -> %s/\n' "$LOG_DIR"
printf '  config -> %s\n' "$CONFIG"
printf '\n'
say "Next:"
printf '  1. edit %s   (interface, camera_ips, lan_subnets)\n' "$CONFIG"
printf '  2. hound config-check %s\n' "$CONFIG"
printf '  3. systemctl enable --now hound   &&   journalctl -u hound -f\n'
printf '\n'
say "Relay agents additionally need, from the collector:"
printf '  [relay] mode="agent", sensor_id, key, url, tls_fingerprint\n'
printf '  Get the pin with: hound relay <collector-config>  ON THE COLLECTOR\n'
