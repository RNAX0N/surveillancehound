#!/bin/sh
#
# SurveillanceHound — one-command OPNsense installer.
#
# Run it straight from a checkout on the firewall:
#
#     sh deploy/opnsense/install.sh
#
# …or bootstrap from nothing (set HOUND_REPO_URL to your fork first):
#
#     fetch -o - https://raw.githubusercontent.com/RNAX0N/surveillancehound/main/deploy/opnsense/install.sh | sh
#
# What it does (all idempotent — safe to re-run, e.g. after a firmware upgrade):
#   1. verifies Python 3.11+ and tcpdump are present (both ship with OPNsense)
#   2. installs the `hound` CLI with ZERO dependencies — a .pth + a tiny wrapper,
#      no pip, no venv, nothing to break on the next OPNsense update
#   3. creates the `hound` service user + /var/lib/hound + /var/log/hound
#   4. drops the MVC plugin + rc.d service + configd glue into place
#   5. refreshes the OPNsense UI so Services > SurveillanceHound appears
#
# It does NOT enable the daemon — you do that from the UI after picking your
# interface and cameras (tick Enable, hit Save & restart).

set -eu

# --- knobs (override via env) -----------------------------------------------
REPO_URL="${HOUND_REPO_URL:-https://github.com/RNAX0N/surveillancehound}"
REPO_BRANCH="${HOUND_REPO_BRANCH:-main}"
SRC_DIR="${HOUND_SRC_DIR:-/usr/local/src/SurveillanceHound}"

HOUND_USER=hound
HOUND_GROUP=hound
STATE_DIR=/var/lib/hound
LOG_DIR=/var/log/hound
BIN=/usr/local/bin/hound

# --- helpers -----------------------------------------------------------------
say()  { printf '\033[36m▸\033[0m %s\n' "$*"; }
ok()   { printf '\033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '\033[33m!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" = "0" ] || die "run as root (su, sudo, or the console root shell)."

# --- 0. locate the repo (run-from-checkout, else fetch it) ------------------
repo_root=""
script="$0"
if [ -f "$script" ]; then
    d=$(cd "$(dirname "$script")" 2>/dev/null && pwd || true)
    if [ -n "$d" ] && [ -f "$d/../../pyproject.toml" ]; then
        repo_root=$(cd "$d/../.." && pwd)
    fi
fi

if [ -z "$repo_root" ]; then
    # The bootstrap fetch only works if the repo is reachable anonymously.
    # surveillancehound is PRIVATE, so the raw one-liner / anonymous clone will
    # 404 unless you make it public or pre-place a credentialed checkout. The
    # supported path is run-from-checkout; this fetch is best-effort.
    say "no checkout detected — fetching $REPO_URL ($REPO_BRANCH) → $SRC_DIR"
    warn "if this 404s, the repo is private — clone it with your credentials to"
    warn "$SRC_DIR first, then re-run this script from there."
    if command -v git >/dev/null 2>&1; then
        if [ -d "$SRC_DIR/.git" ]; then
            git -C "$SRC_DIR" fetch --depth 1 origin "$REPO_BRANCH" && \
                git -C "$SRC_DIR" reset --hard FETCH_HEAD
        else
            git clone --branch "$REPO_BRANCH" --depth 1 "$REPO_URL" "$SRC_DIR"
        fi
    else
        # no git on this box — pull a tarball with FreeBSD's base `fetch`
        slug=$(printf '%s' "$REPO_URL" | sed -E 's#^https?://github.com/##; s#\.git$##')
        tarball="https://codeload.github.com/${slug}/tar.gz/refs/heads/${REPO_BRANCH}"
        tmp=$(mktemp -d)
        ( fetch -qo "$tmp/src.tgz" "$tarball" \
            || curl -fsSL -o "$tmp/src.tgz" "$tarball" ) \
            || die "could not download $tarball (no git, fetch, or curl worked)"
        mkdir -p "$SRC_DIR"
        tar -xzf "$tmp/src.tgz" -C "$SRC_DIR" --strip-components=1
        rm -rf "$tmp"
    fi
    repo_root="$SRC_DIR"
fi
ok "using source at $repo_root"

PLUGIN_SRC="$repo_root/deploy/opnsense/src"
[ -d "$PLUGIN_SRC/opnsense" ] || die "plugin tree missing at $PLUGIN_SRC — bad checkout?"

# --- 1. interpreter + capture tool ------------------------------------------
PY=""
for c in python3.11 python3.12 python3.13 python3; do
    if command -v "$c" >/dev/null 2>&1; then PY=$(command -v "$c"); break; fi
done
[ -n "$PY" ] || die "Python 3.11+ not found. Install it: pkg install -y python311"
"$PY" -c 'import sys; raise SystemExit(0 if sys.version_info[:2] >= (3,11) else 1)' \
    || die "$PY is older than 3.11 (tomllib needs 3.11+). pkg install -y python311"
ok "python: $PY ($("$PY" -c 'import platform;print(platform.python_version())'))"

command -v tcpdump >/dev/null 2>&1 \
    || warn "tcpdump not on PATH — live capture needs it. pkg install -y tcpdump"

# --- 2. install the hound CLI (no pip, zero deps) ---------------------------
say "installing the hound CLI"
SITEPKG=$("$PY" -c 'import site; print(site.getsitepackages()[0])')
printf '%s\n' "$repo_root/src" > "$SITEPKG/surveillancehound.pth"
cat > "$BIN" <<EOF
#!/bin/sh
# SurveillanceHound CLI wrapper (generated by install.sh)
exec "$PY" -m surveillancehound.cli "\$@"
EOF
chmod 0555 "$BIN"
"$BIN" --help >/dev/null 2>&1 || die "hound CLI did not come up — see: $BIN --help"
ok "hound CLI → $BIN"

# --- 3. service user + state/log dirs ---------------------------------------
say "creating service user + directories"
pw groupshow "$HOUND_GROUP" >/dev/null 2>&1 || pw groupadd "$HOUND_GROUP"
pw usershow  "$HOUND_USER"  >/dev/null 2>&1 || \
    pw useradd "$HOUND_USER" -g "$HOUND_GROUP" -s /usr/sbin/nologin -d "$STATE_DIR" \
        -c "SurveillanceHound daemon"
install -d -o "$HOUND_USER" -g "$HOUND_GROUP" -m 0750 "$STATE_DIR"
install -d -o "$HOUND_USER" -g "$HOUND_GROUP" -m 0755 "$LOG_DIR"
ok "user '$HOUND_USER', state $STATE_DIR, logs $LOG_DIR"

# --- 4. drop the plugin into place ------------------------------------------
say "installing the OPNsense plugin"
install -m 0555 "$PLUGIN_SRC/usr/local/etc/rc.d/hound" /usr/local/etc/rc.d/hound
cp -a "$PLUGIN_SRC/opnsense/." /usr/local/opnsense/
chmod 0755 /usr/local/opnsense/scripts/OPNsense/Hound/reload.sh \
           /usr/local/opnsense/scripts/OPNsense/Hound/render_config.py
ok "rc.d service + MVC controllers/model/view + configd actions installed"

# --- 5. refresh the UI ------------------------------------------------------
say "refreshing the OPNsense UI"
if service configd status >/dev/null 2>&1; then
    service configd restart >/dev/null 2>&1 || warn "configd restart failed — restart it by hand"
fi
if command -v configctl >/dev/null 2>&1; then
    configctl webgui restart >/dev/null 2>&1 || warn "webgui restart failed — restart it by hand"
fi
ok "UI refreshed"

cat <<EOF

  ════════════════════════════════════════════════════════════════════
  SurveillanceHound is installed.

  Next — in the OPNsense web UI:
    1. open  Services → SurveillanceHound
    2. pick the Listen interface (camera VLAN or a SPAN/mirror port)
    3. fill in Camera IPs / subnets, NVR IPs, manufacturer allowlist
    4. tick Enable, click  ▸ Save & restart

  That renders /usr/local/etc/hound.toml and starts the daemon. Then watch:
    tail -f $LOG_DIR/hound.log
    hound alerts /usr/local/etc/hound.toml -v

  Extra notifiers (Slack/syslog/SMTP/FTP) go in /etc/hound.toml.local
  (see hound.toml.example) — the rendered hound.toml is overwritten on save.

  Uninstall any time:  sh $repo_root/deploy/opnsense/uninstall.sh
  ════════════════════════════════════════════════════════════════════

EOF
